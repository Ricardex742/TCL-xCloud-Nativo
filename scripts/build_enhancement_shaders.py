#!/usr/bin/env python3
"""Generate GLES 2 luma-network passes from the pinned MIT restoration weights.

Adapted from MatheusDourado/xbox-xcloud-image-enhancer tools/nn_glsl.py.
Separate half-float targets replace WebGL2 MRT; no floating features are clipped to RGBA8.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "app/src/main/assets/enhancement"


def number(value):
    text = "%.7g" % value
    return text if "." in text or "e" in text else text + ".0"


def vector(values):
    return "vec4(" + ",".join(map(number, values)) + ")"


def generate():
    layers = json.loads((ASSETS / "restore.json").read_text())["layers"]
    assert [(x["k"], x["cin"], x["cout"]) for x in layers] == [(3, 1, 8), (1, 8, 8), (3, 8, 1)]
    a, b, c = layers
    header = ("// MIT luma CNN adapted from xCloud Enhanced; see LICENSE.txt. Generated by build_enhancement_shaders.py.\n"
              "precision highp float;\nvarying vec2 tc;\nuniform sampler2D source;\nuniform vec2 frame_size;\n")
    taps = [(x, y) for y in (-1, 0, 1) for x in (-1, 0, 1)]
    for output_block in (0, 1):
        lines = [header, "float Y(vec2 p){return dot(texture2D(source,clamp(p,vec2(.5)/frame_size,1.-vec2(.5)/frame_size)).rgb,vec3(.2126,.7152,.0722));}\n",
                 "void main(){vec4 a=" + vector(a["b"][:4]) + ",b=" + vector(a["b"][4:]) + ";float y;\n"]
        for x, y in taps:
            weights = a["w"][1-y][x+1]
            lines.append(f"y=Y(tc+vec2({number(x)},{number(y)})/frame_size);a+=y*" + vector([weights[0][i] for i in range(4)]) + ";b+=y*" + vector([weights[0][i] for i in range(4, 8)]) + ";\n")
        def matrix(input_block):
            return "mat4(" + ",".join(number(b["w"][0][0][input_block*4+i][output_block*4+o]) for i in range(4) for o in range(4)) + ")"
        lines.append("a=max(a,0.);b=max(b,0.);gl_FragColor=max(" + vector(b["b"][output_block*4:output_block*4+4]) + "+" + matrix(0) + "*a+" + matrix(1) + "*b,0.);}\n")
        (ASSETS / f"neural-{output_block}.frag").write_text("".join(lines))
    lines = [header, "uniform sampler2D features_a,features_b;\nuniform float strength;\nvoid main(){float d=" + number(c["b"][0]) + ";vec2 p;\n"]
    for x, y in taps:
        weights = c["w"][1-y][x+1]
        lines.append(f"p=clamp(tc+vec2({number(x)},{number(y)})/frame_size,vec2(.5)/frame_size,1.-vec2(.5)/frame_size);d+=dot(texture2D(features_a,p)," + vector([weights[i][0] for i in range(4)]) + ")+dot(texture2D(features_b,p)," + vector([weights[i][0] for i in range(4,8)]) + ");\n")
    lines.append("vec3 c=texture2D(source,tc).rgb;d=clamp(strength*d,-.08,.08);d=clamp(d,-min(min(c.r,c.g),c.b),1.-max(max(c.r,c.g),c.b));gl_FragColor=vec4(c+d,1.);}\n")
    (ASSETS / "neural-apply.frag").write_text("".join(lines))


if __name__ == "__main__":
    generate()
